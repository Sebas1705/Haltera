/** The catalogue generated by scripts/catalog and bundled as a Compose resource. */
suspend fun readBundledCatalog(): String = Res.readBytes("files/catalog.json").decodeToString()

/** The generic foods generated by scripts/nutrition and bundled as a Compose resource. */
suspend fun readBundledFoods(): String = Res.readBytes("files/foods.json").decodeToString()

data class StartupState(
    val ready: Boolean = false,
    val failed: Boolean = false,
) : MVIBaseState

sealed interface StartupIntent : MVIBaseIntent {
    data object Start : StartupIntent
}

/**
 * Imports the bundled exercise catalogue and generic foods on launch (each only when it is newer than the
 * installed one), then calls [onImported] (account sign-in and sync start).
 */
class StartupViewModel(
    private val catalog: CatalogRepository,
    private val nutrition: NutritionRepository,
    private val readCatalog: suspend () -> String = ::readBundledCatalog,
    private val readFoods: suspend () -> String = ::readBundledFoods,
    private val onImported: () -> Unit = {},
) : MVIBaseViewModel<StartupState, StartupIntent>(StartupState()) {

    init {
        onEvent(StartupIntent.Start)
    }

    override fun intentHandler(intent: StartupIntent): Job = when (intent) {
        StartupIntent.Start -> execute {
            updateState { StartupState() }
            try {
                catalog.importBundled(readCatalog())
                nutrition.importBundledFoods(readFoods())
                onImported()
                updateState { it.copy(ready = true) }
            } catch (e: CancellationException) {
                throw e
            } catch (@Suppress("TooGenericExceptionCaught") e: Exception) {
                Logger.e(e) { "Catalogue import failed" }
                updateState { it.copy(failed = true) }
            }
        }
    }
}

@Composable
fun StartupScreen(state: StartupState, onRetry: () -> Unit, modifier: Modifier = Modifier) {
    if (state.failed) {
        ErrorScreen(stringResource(Res.string.startup_catalog_error), onRetry = onRetry, modifier = modifier)
        return
    }
    Column(
        modifier = modifier.fillMaxSize().padding(24.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp, Alignment.CenterVertically),
        horizontalAlignment = Alignment.CenterHorizontally,
    ) {
        HalteraLogo(size = 112.dp)
        Text(stringResource(Res.string.app_name), style = MaterialTheme.typography.displayMedium)
        CircularProgressIndicator()
        Text(stringResource(Res.string.startup_loading), color = MaterialTheme.colorScheme.onSurfaceVariant)
    }
}
