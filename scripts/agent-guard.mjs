#!/usr/bin/env node
// PreToolUse guard for AI coding agents (wired in .claude/settings.json, documented in AGENTS.md).
//
// It enforces, mechanically, the rules of AGENTS.md that an agent can break by accident: files that are
// generated or shipped, secrets, and git operations that bypass review. It reads the hook payload from
// stdin and exits 2 (block, reason on stderr) or 0 (allow). It never calls the network.
//
//   node --test scripts/agent-guard.test.mjs
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

/** Files an agent must not write: [pattern on the normalised path, why]. */
const PROTECTED_FILES = [
  [/(^|\/)\.templetry-answers\.yml$/, "it records what generated this project; never hand-edit it (AGENTS.md, template section)"],
  [
    /sqldelight\/databases\/\d+\.db$/,
    "schema snapshots are generated by ./gradlew :data:local:generateCommonMainAppDatabaseSchema and shipped ones are never edited (AGENTS.md, schema section)",
  ],
  [
    /(^|\/)brand\/(logo\.svg|icon\.svg|icon-512\.png)$/,
    "generated from brand/tokens.json; change the tokens and run node scripts/brand.mjs --png (docs/BRAND.md)",
  ],
  [
    /androidApp\/src\/main\/res\/(mipmap-[^/]+\/ic_launcher[^/]*|drawable\/ic_launcher_(foreground|monochrome)\.xml|values\/ic_launcher_colors\.xml|values(-v31)?\/themes\.xml)$/,
    "generated from brand/tokens.json; change the tokens and run node scripts/brand.mjs --png (docs/BRAND.md)",
  ],
  [/iosApp\/iosApp\/Assets\.xcassets\/AppIcon\.appiconset\//, "generated from brand/tokens.json (docs/BRAND.md)"],
];

/** Secret-bearing files: never written and never read through a shell reader. Secrets live in Doppler. */
const SECRET_FILE = /(^|[\\/\s"'=])(google-services\.json|GoogleService-Info\.plist|secrets\.properties|\.env(\.[\w.-]+)?|[\w.-]+\.(keystore|jks))(?=$|[\s"'])/;

const SHELL_READERS = /\b(cat|type|less|more|head|tail|bat|sed|awk|grep|rg|Get-Content|gc|Select-String|cp|copy|mv|move|scp|curl)\b/i;

const normalise = (p) => String(p ?? "").replace(/\\/g, "/");

/**
 * Decides one tool call.
 * @param {{tool_name?: string, tool_input?: Record<string, unknown>}} call hook payload
 * @param {{branch?: string}} env current git branch, injected so tests need no repository
 * @returns {{block: boolean, reason?: string}}
 */
export function evaluate(call, env = {}) {
  const tool = call.tool_name ?? "";
  const input = call.tool_input ?? {};

  if (tool === "Edit" || tool === "Write" || tool === "NotebookEdit") {
    const path = normalise(input.file_path ?? input.notebook_path);
    if (SECRET_FILE.test(path)) {
      return deny(`${path} may hold secrets. Secrets live only in Doppler and are never written by an agent (AGENTS.md).`);
    }
    for (const [pattern, why] of PROTECTED_FILES) {
      if (pattern.test(path)) return deny(`${path} must not be edited by hand: ${why}.`);
    }
    return { block: false };
  }

  if (tool === "Bash") {
    const cmd = String(input.command ?? "");
    if (/\bgit\b[^|;&]*\bpush\b[^|;&]*(--force\b|--force-with-lease\b|\s-f\b)/.test(cmd)) {
      return deny("force pushes are not allowed; open a new commit instead.");
    }
    if (/\bgit\b[^|;&]*\b(commit|push)\b[^|;&]*--no-verify\b/.test(cmd)) {
      return deny("hooks must not be skipped (--no-verify).");
    }
    if (/\bgit\b[^|;&]*\bpush\b[^|;&]*(?:[\s:]|refs\/heads\/)(?:main|master)(?=$|[\s;&|"'])/.test(cmd)) {
      return deny("pushing to main or master directly is not allowed; push your branch and open a pull request.");
    }
    if (/\bgit\b[^|;&]*\b(commit|push)\b/.test(cmd) && ["main", "master"].includes(env.branch ?? "")) {
      return deny(`you are on ${env.branch}: create a branch first (feature/, fix/, chore/ or docs/, see CONTRIBUTING.md).`);
    }
    if (/\bdoppler\s+secrets\b/.test(cmd) && !/--only-names\b/.test(cmd)) {
      return deny("do not print Doppler secret values; use --only-names, or doppler run -- <command> so the value stays out of the output.");
    }
    if (SECRET_FILE.test(cmd) && SHELL_READERS.test(cmd)) {
      return deny("this command reads or copies a file that may hold secrets (AGENTS.md).");
    }
  }
  return { block: false };
}

const deny = (reason) => ({ block: true, reason: `Blocked by scripts/agent-guard.mjs: ${reason}` });

function currentBranch() {
  try {
    return execFileSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
}

async function main() {
  let raw = "";
  for await (const chunk of process.stdin) raw += chunk;
  let call;
  try {
    call = JSON.parse(raw);
  } catch {
    return 0; // not a hook payload: never block on a parse problem
  }
  const result = evaluate(call, { branch: call.tool_name === "Bash" ? currentBranch() : "" });
  if (result.block) {
    console.error(result.reason);
    return 2;
  }
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = await main();
