#!/usr/bin/env node
// Brand assets from brand/tokens.json (docs/BRAND.md): the logo SVGs, the Android launcher icon
// (adaptive, monochrome and PNG), the Android 12+ splash theme and the iOS app icon. Run it after
// changing the brand:
//
//   node scripts/brand.mjs            write every generated text file
//   node scripts/brand.mjs --check    fail if a generated text file is out of date or a PNG is missing (CI)
//   node scripts/brand.mjs --png      also render the PNG icons (Android density folders, iOS, Play)
//                                     with a headless Edge or Chrome
//
// The app's own colours live in core/ui BrandColors.kt and the logo in IronlogLogo.kt;
// BrandTokensTest checks they match this file.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const brand = JSON.parse(readFileSync(join(root, "brand/tokens.json"), "utf8"));
const L = brand.logo;
const header = (comment) => comment.replace("%", "Generated by scripts/brand.mjs from brand/tokens.json: do not edit.");
const n = (v) => Number(v.toFixed(3)).toString();
const argb = (hex) => "#FF" + hex.slice(1).toUpperCase();

// ── Logo geometry ─────────────────────────────────────────────────────────────
// Drawing order: the vertical bar behind the two beams, the plates on top.
const layers = [
  { shapes: L.bars, color: L.bar },
  { shapes: L.beams, color: L.beam },
  { shapes: L.plates, color: L.plate },
];
const shapes = layers.flatMap((layer) => layer.shapes);

/** A rounded rectangle as path data (absolute commands, valid in SVG and Android vectors). */
const roundRect = ({ x, y, w, h, r }) =>
  `M${n(x + r)},${n(y)} H${n(x + w - r)} A${n(r)},${n(r)} 0 0 1 ${n(x + w)},${n(y + r)} ` +
  `V${n(y + h - r)} A${n(r)},${n(r)} 0 0 1 ${n(x + w - r)},${n(y + h)} H${n(x + r)} ` +
  `A${n(r)},${n(r)} 0 0 1 ${n(x)},${n(y + h - r)} V${n(y + r)} A${n(r)},${n(r)} 0 0 1 ${n(x + r)},${n(y)} Z`;

// Adaptive icons are 108 dp with a 66 dp safe circle in the middle. The drawing is scaled around
// the centre so its farthest point (a plate's outer corner) stays inside that circle.
const centre = L.grid / 2;
const reach = Math.max(...shapes.map(({ x, y, w, h, r }) => {
  const cx = Math.max(Math.abs(x + r - centre), Math.abs(x + w - r - centre));
  const cy = Math.max(Math.abs(y + r - centre), Math.abs(y + h - r - centre));
  return Math.hypot(cx, cy) + r;
}));
const safeScale = Math.floor(((L.safeZone / 2) / reach) * 100) / 100;

// ── SVG ───────────────────────────────────────────────────────────────────────
const svgShapes = (mono) =>
  layers.map(({ shapes: list, color }) => list.map((s) => `<path d="${roundRect(s)}" fill="${mono ?? color}"/>`).join("")).join("");
const svg = (body, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${L.grid} ${L.grid}"${title ? ` role="img" aria-label="${title}"` : ""}>${body}</svg>\n`;
/** The logo as IronlogLogo draws it: graphite rounded square. */
const logoSvg = svg(`<rect width="${L.grid}" height="${L.grid}" rx="${L.corner}" fill="${L.background}"/>` + svgShapes(), "Ironlog");
/** Full-bleed square for the stores and iOS, which round the corners themselves. */
const iconSvg = svg(`<rect width="${L.grid}" height="${L.grid}" fill="${L.background}"/>` + svgShapes());
/** Round variant for launchers that ask for ic_launcher_round. */
const roundSvg = svg(`<circle cx="${centre}" cy="${centre}" r="${centre}" fill="${L.background}"/>` + svgShapes());

// ── Android ───────────────────────────────────────────────────────────────────
const vectorPaths = (mono) =>
  layers.flatMap(({ shapes: list, color }) => list.map((s) => `        <path
            android:fillColor="${mono ?? argb(color)}"
            android:pathData="${roundRect(s)}" />`)).join("\n");
const vector = (mono) => `<?xml version="1.0" encoding="utf-8"?>
${header("<!-- % -->")}
<!-- Barbell-I logo scaled by ${safeScale} around the centre to fit the ${L.safeZone} dp safe zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${L.grid}dp"
    android:height="${L.grid}dp"
    android:viewportWidth="${L.grid}"
    android:viewportHeight="${L.grid}">
    <group
        android:pivotX="${centre}"
        android:pivotY="${centre}"
        android:scaleX="${safeScale}"
        android:scaleY="${safeScale}">
${vectorPaths(mono)}
    </group>
</vector>
`;
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
${header("<!-- % -->")}
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;
const colors = `<?xml version="1.0" encoding="utf-8"?>
${header("<!-- % -->")}
<resources>
    <color name="ic_launcher_background">${L.background}</color>
</resources>
`;
const theme = (splash) => `<?xml version="1.0" encoding="utf-8"?>
${header("<!-- % -->")}
<resources>
    <style name="Theme.Ironlog" parent="@android:style/Theme.Material.NoActionBar">${splash ? `
        <!-- Android 12+ splash screen: the adaptive foreground on graphite. -->
        <item name="android:windowSplashScreenBackground">@color/ic_launcher_background</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/ic_launcher_foreground</item>` : ""}
    </style>
</resources>
`;

// ── iOS ───────────────────────────────────────────────────────────────────────
const xcassets = `{
  "info" : { "author" : "xcode", "version" : 1 }
}
`;
const appIconSet = `{
  "images" : [
    { "filename" : "AppIcon.png", "idiom" : "universal", "platform" : "ios", "size" : "1024x1024" }
  ],
  "info" : { "author" : "xcode", "version" : 1 }
}
`;

const res = "composeApp/src/androidMain/res";
const assets = "iosApp/iosApp/Assets.xcassets";
const files = {
  "brand/logo.svg": logoSvg,
  "brand/icon.svg": iconSvg,
  [`${res}/drawable/ic_launcher_foreground.xml`]: vector(null),
  // Themed icons (Android 13+): one colour, the launcher tints it.
  [`${res}/drawable/ic_launcher_monochrome.xml`]: vector("#FFFFFFFF"),
  [`${res}/mipmap-anydpi-v26/ic_launcher.xml`]: adaptive,
  [`${res}/mipmap-anydpi-v26/ic_launcher_round.xml`]: adaptive,
  [`${res}/values/ic_launcher_colors.xml`]: colors,
  [`${res}/values/themes.xml`]: theme(false),
  [`${res}/values-v31/themes.xml`]: theme(true),
  [`${assets}/Contents.json`]: xcassets,
  [`${assets}/AppIcon.appiconset/Contents.json`]: appIconSet,
};

// PNGs: rendered with --png from the SVGs above. Android 7 has no adaptive icons, and Firebase App
// Distribution (App Tester) cannot read adaptive ones, so every density folder gets PNGs too.
const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
const pngs = [
  ...Object.entries(densities).flatMap(([density, size]) => [
    { source: logoSvg, size, path: `${res}/mipmap-${density}/ic_launcher.png`, transparent: true },
    { source: roundSvg, size, path: `${res}/mipmap-${density}/ic_launcher_round.png`, transparent: true },
  ]),
  { source: iconSvg, size: 1024, path: `${assets}/AppIcon.appiconset/AppIcon.png`, transparent: false },
  { source: iconSvg, size: 512, path: "brand/icon-512.png", transparent: false },
];

const check = process.argv.includes("--check");
const stale = [];
for (const [path, content] of Object.entries(files)) {
  const file = join(root, path);
  const current = existsSync(file) ? readFileSync(file, "utf8").replaceAll("\r\n", "\n") : null;
  if (current === content) continue;
  if (check) {
    stale.push(path);
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log("wrote", path);
  }
}
if (check) {
  const missing = pngs.map((p) => p.path).filter((path) => !existsSync(join(root, path)));
  if (stale.length || missing.length) {
    if (stale.length) console.error("Brand files out of date (run `node scripts/brand.mjs`):\n  " + stale.join("\n  "));
    if (missing.length) console.error("Brand PNGs missing (run `node scripts/brand.mjs --png`):\n  " + missing.join("\n  "));
    process.exit(1);
  }
  console.log(`Brand files up to date (adaptive icon scale ${safeScale})`);
}

if (process.argv.includes("--png")) {
  const browsers = [
    "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
    "C:/Program Files/Google/Chrome/Application/chrome.exe",
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium",
  ];
  const browser = browsers.find(existsSync);
  if (!browser) throw new Error("No Edge or Chrome found to render the PNG icons");
  for (const { source, size, path, transparent } of pngs) {
    const page = join(tmpdir(), "ironlog-icon.html");
    writeFileSync(page, `<!doctype html><html><body style="margin:0">${source.replace("<svg ", `<svg width="${size}" height="${size}" style="display:block" `)}</body></html>`);
    const out = join(root, path);
    mkdirSync(dirname(out), { recursive: true });
    execFileSync(browser, ["--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
      ...(transparent ? ["--default-background-color=00000000"] : []),
      `--window-size=${size},${size}`, `--screenshot=${out}`, "file:///" + page.replaceAll("\\", "/")], { stdio: "ignore", timeout: 60_000 });
    rmSync(page);
    console.log("wrote", path);
  }
}
